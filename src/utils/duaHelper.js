const MASTER_DUA = {
  title: 'صيغة الحمد الشاملة',
  dua: '«اللَّهُمَّ لَكَ الْحَمْدُ حَتَّى تَرْضَى، وَلَكَ الْحَمْدُ إِذَا رَضِيتَ، وَلَكَ الْحَمْدُ بَعْدَ الرِّضَا، وَلَكَ الْحَمْدُ عَلَى كُلِّ حَالٍ»',
  source: 'مأثور'
};

export function getBlessingGratitudeDua(blessing) {
  if (!blessing) return MASTER_DUA;

  // 1. Check if blessing has a specific tag match
  if (blessing.tags && Array.isArray(blessing.tags)) {
    for (const tag of blessing.tags) {
      if (SPECIFIC_DUAS[tag]) {
        return SPECIFIC_DUAS[tag];
      }
    }
  }

  // Check title keywords
  const title = blessing.title || '';
  if (title.includes('ليل') || title.includes('نوم') || title.includes('سكون')) {
    return SPECIFIC_DUAS['سكون'];
  }
  if (title.includes('صباح') || title.includes('فجر') || title.includes('شروق')) {
    return SPECIFIC_DUAS['صباح'];
  }
  if (title.includes('مطر') || title.includes('غيث')) {
    return SPECIFIC_DUAS['مطر'];
  }
  if (title.includes('ستر') || title.includes('خصوصية')) {
    return SPECIFIC_DUAS['ستر'];
  }
  if (title.includes('طعام') || title.includes('ماء') || title.includes('شراب')) {
    return SPECIFIC_DUAS['طعام'];
  }

  // 2. Check category match
  if (blessing.category && CATEGORY_DUAS[blessing.category]) {
    return CATEGORY_DUAS[blessing.category];
  }

  return MASTER_DUA;
}
